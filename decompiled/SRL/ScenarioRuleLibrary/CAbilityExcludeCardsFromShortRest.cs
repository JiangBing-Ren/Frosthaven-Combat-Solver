using System.Collections.Generic;

namespace ScenarioRuleLibrary;

public class CAbilityExcludeCardsFromShortRest : CAbilityTargeting
{
	public CAbilityExcludeCardsFromShortRest()
		: base(EAbilityType.ExcludeCardsFromShortRest)
	{
	}

	public override bool ActorIsApplying(CActor actorApplying, List<CActor> actorsAppliedTo)
	{
		base.ActorIsApplying(actorApplying, actorsAppliedTo);
		CActorIsApplyingConditionActiveBonus_MessageData message = new CActorIsApplyingConditionActiveBonus_MessageData(AnimOverload, actorApplying)
		{
			m_Ability = this,
			m_ActorsAppliedTo = actorsAppliedTo
		};
		ScenarioRuleClient.MessageHandler(message);
		return false;
	}

	public override bool ApplyToActor(CActor actor)
	{
		if (base.ApplyToActor(actor))
		{
			AbilityHasHappened = true;
			if (!(actor is CPlayerActor))
			{
				Log.ErrorWithReport("Trying to apply Exclude Cards From Short Rest to a non player actor");
			}
			if (m_PositiveConditions.Count > 0)
			{
				ProcessPositiveStatusEffects(actor);
			}
		}
		return true;
	}

	public override bool CanApplyActiveBonusTogglesTo()
	{
		return false;
	}

	public override bool IsPositive()
	{
		return true;
	}
}
